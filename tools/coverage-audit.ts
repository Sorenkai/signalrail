/**
 * Timetable coverage audit (P6, D-036): runs the service planner on a dataset's dated snapshot
 * and groups every service by the movement it needs, using a hand-authored movement-group
 * table, then writes a machine-readable JSON and a human-readable Markdown report.
 *
 *   npm run data:coverage -- --dataset carlisle --date 2026-11-04 \
 *     --groups docs/pilots/carlisle-p7-movement-groups.json \
 *     [--patterns <ids>] [--baseline-patterns <ids>] \
 *     [--phase P7] [--decision D-037] [--baseline-label "P6 patterns"] \
 *     [--json docs/pilots/carlisle-p7-coverage.json] [--md docs/pilots/CARLISLE_P7_COVERAGE.md]
 *
 * `--baseline-patterns` reruns the same planner on the same snapshot with only the listed
 * patterns, for a before/after comparison. `--patterns` restricts the "current" plan the same
 * way, so an earlier phase's report can be reproduced from today's files (P7: the P6 report is
 * regenerated with the two P6 patterns; IMPORTING.md). `--phase`, `--decision` and
 * `--baseline-label` only label the report (defaults: the P6 report's wording). Nothing here
 * changes a dataset or a classification; blocked-group sizes are upper-bound estimates.
 */
import { writeFileSync } from "node:fs";
import { loadDataset } from "../src/data/loadDataset.ts";
import {
  MovementGroupsFile,
  auditCoverage,
  type CoverageAudit,
} from "../src/reconcile/timetableCoverage.ts";
import {
  DEFAULT_POLICY,
  createWorld,
  summarisePlan,
  timetableSessionConfig,
} from "../src/sim/index.ts";
import { flags, path, readJson, writeJson } from "./lib.ts";

const args = flags();
const id = args.dataset ?? "carlisle";
const date = args.date;
if (!date) throw new Error("--date YYYY-MM-DD is required");
if (!args.groups) throw new Error("--groups <movement-groups.json> is required");
const table = MovementGroupsFile.parse(readJson(path(args.groups)));

const { input, schemaIssues } = loadDataset(path("data"), id);
if (!input || schemaIssues.length > 0)
  throw new Error(`dataset ${id} did not load: ${schemaIssues.map((i) => i.message).join("; ")}`);
const snapshot = (input.timetables ?? []).find((t) => t.date === date);
if (!snapshot) throw new Error(`no timetable snapshot for ${date} in ${id}/timetables`);
if (!input.servicePatterns || !input.signalling || !input.control)
  throw new Error(`${id} needs service-patterns.json, signalling.json and control.json`);

function plan(patternIds?: string[]) {
  const patterns = structuredClone(input!.servicePatterns!);
  if (patternIds) patterns.patterns = patterns.patterns.filter((p) => patternIds.includes(p.id));
  return createWorld(
    {
      infrastructure: input!.infrastructure,
      signalling: input!.signalling!,
      control: input!.control!,
      sources: input!.sources,
      ...(input!.gameRules ? { gameRules: input!.gameRules } : {}),
      ...(input!.playableArea ? { playableArea: input!.playableArea } : {}),
      timetable: { snapshot: snapshot!, patterns, config: timetableSessionConfig(date!) },
    },
    DEFAULT_POLICY,
    {},
  ).timetable!;
}

const phase = args.phase ?? "P6";
const decision = args.decision ?? "D-036";
const baselineLabel = args["baseline-label"] ?? "P5 pattern only";
const currentIds = args.patterns?.split(",");
const current = plan(currentIds);
const audit = auditCoverage(current, snapshot, table);
const baselineIds = args["baseline-patterns"]?.split(",");
const baseline = baselineIds ? summarisePlan(plan(baselineIds)) : null;
const baselineAudit = baselineIds ? auditCoverage(plan(baselineIds), snapshot, table) : null;
const summary = summarisePlan(current);

const report = {
  $comment: `Generated by tools/coverage-audit.ts (${phase}, ${decision}). Classifications are the planner's; group sizes of blocked groups are upper-bound estimates. Do not edit by hand.`,
  datasetId: id,
  date,
  snapshotId: current.snapshotId,
  sessionConfig: current.config,
  patterns: input.servicePatterns.patterns
    .map((p) => p.id)
    .filter((p) => !currentIds || currentIds.includes(p)),
  baseline: baseline ? { patterns: baselineIds, ...baseline } : null,
  current: summary,
  byFamily: audit.byFamily,
  baselineByFamily: baselineAudit?.byFamily ?? null,
  groups: audit.groups,
  blockers: table.blockers,
  unmatched: audit.unmatched,
  inconsistent: audit.inconsistent,
  services: audit.services,
};
if (args.json) writeJson(path(args.json), report);

const pct = (n: number, t: number) => `${((100 * n) / t).toFixed(1)}%`;
const classes = ["representable", "approximated", "unsupported", "invalid"] as const;
function markdown(a: CoverageAudit): string {
  const L: string[] = [];
  L.push(`# Carlisle timetable coverage audit (${phase})`, "");
  L.push(
    `Generated by \`tools/coverage-audit.ts\` from \`${id}/timetables/${date}.json\` (${current.snapshotId}), the service patterns and \`${args.groups}\`. Do not edit by hand; see DECISION_LOG ${decision}.`,
    "",
    `Session settings: train length ${current.config.trainLengthMm / 1000} m and speed ${current.config.trainSpeedMmPerS / 1000} m/s for every service (game settings, not timetable data).`,
    "",
    "Classifications come from the planner (`buildServicePlan`). For blocked groups, the service counts are **upper-bound estimates** of what removing every listed blocker could unlock: each service would still need an exact pattern. They are not results.",
    "",
    "## Classification",
    "",
    `| Class | Before (${baselineLabel}) | After (${phase}) | Change |`,
    "| --- | ---: | ---: | ---: |",
  );
  for (const c of classes) {
    const b = baseline?.byClass[c] ?? 0;
    const n = summary.byClass[c];
    L.push(
      `| ${c} | ${b} (${pct(b, summary.total)}) | ${n} (${pct(n, summary.total)}) | ${n - b >= 0 ? "+" : ""}${n - b} |`,
    );
  }
  L.push(`| total | ${baseline?.total ?? "-"} | ${summary.total} | |`, "");
  L.push(
    "## By movement family",
    "",
    "| Family | Runnable before | Runnable after | Unsupported after |",
    "| --- | ---: | ---: | ---: |",
  );
  for (const [f, c] of Object.entries(a.byFamily)) {
    const b = baselineAudit?.byFamily[f as keyof CoverageAudit["byFamily"]];
    L.push(
      `| ${f} | ${b ? b.representable + b.approximated : "-"} | ${c.representable + c.approximated} | ${c.unsupported} |`,
    );
  }
  L.push(
    "",
    "## Movement groups",
    "",
    "| Group | Family | Services | Runnable | Unsupported | Distinct paths | Blockers |",
    "| --- | --- | ---: | ---: | ---: | ---: | --- |",
  );
  for (const g of a.groups)
    L.push(
      `| \`${g.id}\`: ${g.label} | ${g.family} | ${g.services} | ${g.byClass.representable + g.byClass.approximated} | ${g.byClass.unsupported} | ${g.distinctPaths} | ${g.blockers.join(", ") || "none"} |`,
    );
  L.push("", "## Blockers", "");
  for (const b of table.blockers) {
    const used = a.groups.filter((g) => g.blockers.includes(b.id));
    L.push(
      `### ${b.id} (${b.kind}, evidence: ${b.evidence})`,
      "",
      b.summary,
      "",
      `- **Records:** ${b.records.map((r) => `\`${r}\``).join(", ") || "-"}`,
      `- **Needed:** ${b.needed}`,
      `- **Proposed change:** ${b.proposedChange}`,
      `- **Groups:** ${used.map((g) => `\`${g.id}\` (${g.byClass.unsupported})`).join(", ") || "none"}`,
      "",
    );
  }
  L.push("## Unsupported services by group", "");
  for (const g of a.groups) {
    const members = a.services.filter(
      (s) => s.groupId === g.id && s.classification === "unsupported",
    );
    if (members.length === 0) continue;
    L.push(
      `### \`${g.id}\` (${members.length})`,
      "",
      "| Service | Headcode | Reasons | Timing points around play |",
      "| --- | --- | --- | --- |",
    );
    for (const s of members)
      L.push(
        `| ${s.serviceId} | ${s.headcode ?? "-"} | ${s.reasons.join(", ")} | ${s.observedPath} |`,
      );
    L.push("");
  }
  return L.join("\n");
}
if (args.md) writeFileSync(path(args.md), markdown(audit) + "\n");

console.log(`=== ${id} ${date}: ${current.snapshotId} ===`);
if (baseline) console.log("baseline:", JSON.stringify(baseline.byClass));
console.log("current: ", JSON.stringify(summary.byClass), "of", summary.total);
for (const g of audit.groups)
  console.log(
    `  ${g.id.padEnd(26)} ${String(g.services).padStart(4)}  runnable ${g.byClass.representable + g.byClass.approximated}  unsupported ${g.byClass.unsupported}  paths ${g.distinctPaths}`,
  );
if (audit.unmatched.length) console.log("UNMATCHED:", audit.unmatched.join(", "));
if (audit.inconsistent.length) console.log("INCONSISTENT GROUPS:", audit.inconsistent.join(", "));
